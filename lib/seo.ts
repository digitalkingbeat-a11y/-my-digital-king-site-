export function getCityBySlug(slug: string) {
  return serviceAreaCities.find((city) => city.slug === slug);
}

export function getAllContentEntries() {
  return contentCollections.flatMap((collection) =>
    collection.entries.map((entry) => ({
      ...entry,
      type: collection.type,
      path: `${collection.basePath}/${entry.slug}`,
    }))
  );
}

export function getCollection(basePath: string) {
  return contentCollections.find((collection) => collection.basePath === basePath);
}

export function getContentEntry(basePath: string, slug: string) {
  const collection = getCollection(basePath);
  const entry = collection?.entries.find((item) => item.slug === slug);

  if (!collection || !entry) {
    return undefined;
  }

  return {
    ...entry,
    type: collection.type,
    path: `${collection.basePath}/${entry.slug}`,
  };
}

export function getFaqSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((faq) => ({
      "@type": "Question",
      name: faq.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: faq.answer,
      },
    })),
  };
}
